def _na(v):
    return v is None or v is pd.NA or (isinstance(v, float) and math.isnan(v))


def _py(v):
    """numpy / pandas scalar -> Python (None for NaN / NA)."""
    if _na(v):
        return None
    return v.item() if hasattr(v, "item") else v


# ------------------------------------------------------------------ inputs (module-scoped, built once)
@functools.lru_cache(maxsize=None)
def baskets():
    return pd.read_parquet(FIX / "baskets.parquet")


@functools.lru_cache(maxsize=None)
def basket_by_event():
    return baskets().set_index("event_id")


@functools.lru_cache(maxsize=None)
def marks():
    return pd.read_parquet(FIX / "reporter_marks.parquet")


@functools.lru_cache(maxsize=None)
def spy_daily():
    return pd.read_parquet(FIX / "spy_daily.parquet").set_index("date")


@functools.lru_cache(maxsize=None)
def legs_by_point():
    legs = pd.read_parquet(FIX / "leg_marks.parquet")
    return {k: g for k, g in legs.groupby(["event_id", "mark"], sort=False)}


@functools.lru_cache(maxsize=None)
def signals():
    return pd.read_parquet(FIX / "event_signal.parquet").set_index("event_id")


@functools.lru_cache(maxsize=None)
def long_file(name):
    return pd.read_parquet(FIX / name)


@functools.lru_cache(maxsize=None)
def prod_series(fixture, variant, exit_code=None, level=None):
    return wt.wide_slice(long_file(fixture), variant, exit_code, level).set_index("trade_day")


@functools.lru_cache(maxsize=None)
def rebuilt(variant):
    """variant dir -> ({exit: daily frame by trade_day}, utilization frame by trade_day): producer on the trace."""
    cap, fee = VARIANT[variant]
    dailies, util = wt.rebuild_scope(baskets(), spy_daily(), SCOPES, EXITS, cap=cap, fee=fee, marks=marks(), days=DAYS)
    return {e: d.set_index("trade_day") for e, d in dailies.items()}, util.set_index("trade_day")


@functools.lru_cache(maxsize=None)
def rebuilt_stop(variant):
    cap, fee = VARIANT[variant]
    out = wt.rebuild_stop(baskets(), spy_daily(), SCOPES, EXITS, fee=fee, marks=marks(), days=DAYS)
    return {k: d.set_index("trade_day") for k, d in out.items()}


@functools.lru_cache(maxsize=None)
def trace_ok(fee):
    return wt.trace_ok(baskets(), marks(), fee)


@functools.lru_cache(maxsize=None)
def stats(scope, variant, exit_code, source):
    """window stats {portfolio: stats} + the cell's n_events / n_trades; source 'rebuilt' | 'production'."""
    daily = rebuilt(variant)[0][exit_code] if source == "rebuilt" else prod_series("daily_returns.parquet",
                                                                                     variant, exit_code)
    st = wt.window_stats(daily, CELL[scope])
    cnt = wt.cell_counts(trace_ok(VARIANT[variant][1]), scope, CON, UNI)
    return {pk: ({**cnt, **v} if pk != wt.SPY_PORTFOLIO else dict(v)) for pk, v in st.items()}


@functools.lru_cache(maxsize=None)
def scope_counts(scope):
    return wt.event_scope_counts(baskets(), marks(), scope, DAYS)


@functools.lru_cache(maxsize=None)
def fee_drag(scope, cap, exit_code):
    return wt.fee_drag(baskets(), marks(), scope, cap, FEE_MILLS, DAYS, CELL[scope])


def _assert_stat(got, want, what):
    if _na(want):
        assert _na(got), (what, got, want)
    elif isinstance(want, (bool, str)) or isinstance(got, (bool, np.bool_, str)):
        assert got == want, (what, got, want)
    elif isinstance(want, int):
        assert got == want, (what, got, want)
    else:
        assert abs(float(got) - want) <= FLOAT_TOL_STATS, (what, got, want)


# ------------------------------------------------------------------ A: every mark of every event
@pytest.mark.parametrize("event_id,mark,expected", EP.EVENT_MARKS,
                         ids=[f"{e}-pnl_{m}" for e, m, _ in EP.EVENT_MARKS])
def test_event_mark(event_id, mark, expected):
    legs = legs_by_point()[(event_id, mark)]
    assert len(legs) and (legs["event_id"] == event_id).all()
    got = wt.recompute_mark(legs)                      # evaluate.leg_pnl_sum over the booked legs
    row = basket_by_event().loc[event_id]
    prod = _py(row[wt.pnl_col(mark)])
    if expected is None:                               # day-N session not in the panel
        assert got is None and prod is None and not legs["session_covered"].any()
        return
    assert row["status"] == "ok"
    assert prod == expected                            # the literal is the production shard value
    assert abs(got - prod) <= MARK_TOL, (got, prod)
    assert abs(got - expected) <= MARK_TOL, (got, expected)


# ------------------------------------------------------------------ B: every event row
@pytest.mark.parametrize("event_id,status,skip_reason,direction,gap", EP.EVENT_ROWS,
                         ids=[str(r[0]) for r in EP.EVENT_ROWS])
def test_event_row(event_id, status, skip_reason, direction, gap):
    row = basket_by_event().loc[event_id]
    s = signals().loc[event_id]
    sig = fade_the_gap(_py(s["signal_price_928"]), _py(s["prev_close"]))
    assert row["status"] == status and _py(row["skip_reason"]) == skip_reason
    assert row["trade_day"] == s["trade_day"] and row["event_symbol"] == s["reporter"]
    assert s["n_reporter_premarket_prints"] > 0                     # signal_price came from >= 1 print
    assert sig.gap == _py(row["signal_return_928_vs_prev_close"]) == gap == _py(s["gap"])
    assert sig.direction == _py(row["direction"]) == direction == _py(s["direction"])
    assert _py(s["reporter_entry_930"]) is not None                # reporter_no_open_bar would have skipped
    entry = marks().set_index("event_id").loc[event_id, wt.MARKS_PRICE]
    assert _py(s["reporter_entry_930"]) == _py(entry)               # == diagnostics/reporter_marks
    if status == "ok":
        assert skip_reason is None
        rep = legs_by_point()[(event_id, "close")]
        rep = rep[rep["is_reporter"]]
        assert len(rep) == 1 and rep["entry_price"].iloc[0] == _py(s["reporter_entry_930"])
        assert np.sign(rep["weight"].iloc[0]) == direction             # long reporter on +1, short on -1
    else:
        assert status == "skip" and skip_reason.startswith("construction:")


# ------------------------------------------------------------------ C: per-share fee of every ok row
@pytest.mark.parametrize("event_id,fee_per_dollar", EP.FEE_ROWS, ids=[str(e) for e, _ in EP.FEE_ROWS])
def test_fee_row(event_id, fee_per_dollar):
    ok = trace_ok(0)
    row = ok[ok["event_id"] == event_id]
    assert len(row) == 1
    net = fees.apply_per_share_fee(row, FEE_MILLS / 1000)
    assert net["fee_per_dollar"].iloc[0] == fee_per_dollar
    for c in fees.pnl_columns(row):
        g, n = row[c].iloc[0], net[c].iloc[0]
        if _na(g):
            assert _na(n), c
        else:
            assert n == g - net["fee_per_dollar"].iloc[0], c
            assert n < g, c
    # the fee-variant trace rows carry the same fee (what rebuild_scope nets for _fee5m)
    assert trace_ok(FEE_MILLS).set_index("event_id").loc[event_id, "fee_per_dollar"] == fee_per_dollar


