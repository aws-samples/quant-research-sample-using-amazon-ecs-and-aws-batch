def test_net_below_gross(scope, cap, exit_code, portfolio):
    lit = {(r[1], r[4]): r[5] for r in EP.TOTALS
           if r[0] == scope and r[2] == exit_code and r[3] == portfolio}
    gross_v, net_v = wt.variant_dir(cap, 0), wt.variant_dir(cap, FEE_MILLS)
    assert lit[(net_v, "total_pct")] < lit[(gross_v, "total_pct")]
    assert lit[(net_v, "ann_ret_pct")] < lit[(gross_v, "ann_ret_pct")]
    assert lit[(net_v, "n_trades")] == lit[(gross_v, "n_trades")]          # fees never drop a trade
    for v in (gross_v, net_v):
        assert stats(scope, v, exit_code, "rebuilt")[portfolio]["total_pct"] == pytest.approx(
            lit[(v, "total_pct")], abs=FLOAT_TOL_STATS)


