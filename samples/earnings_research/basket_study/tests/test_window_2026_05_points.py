# ------------------------------------------------------------------ I: viewer summaries
VIEWER = json.loads((FIX / "expected_viewer.json").read_text())["queries"]


@pytest.mark.parametrize("qs", sorted(VIEWER))
def test_viewer_summary(qs):
    q = {k: v[0] for k, v in parse_qs(qs).items()}
    vd = wt.variant_dir(int(q["cap"]), int(q["fee"]))
    assert (q["construction"], q["universe"]) == (CON, UNI) and q["start"] == DAYS[0]
    st = VIEWER[qs]["stats"]
    lit = {(r[3], r[4]): r[5] for r in EP.TOTALS if r[0] == q["scope"] and r[1] == vd and r[2] == q["exit"]}
    reb = stats(q["scope"], vd, q["exit"], "rebuilt")
    for pk in list(wt.PORTFOLIO_KEYS.values()) + [wt.SPY_PORTFOLIO]:
        assert st[pk]["n_days"] == len(DAYS)
        for stat in ("sharpe", "total_pct", "max_dd_pct"):
            assert abs(st[pk][stat] - lit[(pk, stat)]) <= FLOAT_TOL_STATS, (pk, stat)
            assert abs(st[pk][stat] - reb[pk][stat]) <= FLOAT_TOL_STATS, (pk, stat)
        if pk == wt.SPY_PORTFOLIO:
            continue
        n_trades = lit[(pk, "n_trades")]
        if st[pk]["n_trades_floor"]:                    # utilization hit 100 % on some day: count is a floor
            assert st[pk]["n_trades"] <= n_trades
        else:
            assert st[pk]["n_trades"] == n_trades


# ------------------------------------------------------------------ production full-history stats (pinned)
@pytest.mark.pinned_only
@pytest.mark.parametrize("variant,exit_code,scope,portfolio,stat,expected", EP.PROD_STATS,
                         ids=[f"{SHORT[v]}-{e}-{s}-{p}-{st}" for v, e, s, p, st, _ in EP.PROD_STATS])
def test_production_stats(variant, exit_code, scope, portfolio, stat, expected):
    """PINNED ONLY: the full-history production row == literal (not rebuildable from a 21-day trace)."""
    ps = long_file("portfolio_stats.parquet")
    pk = ps["portfolio"].map(lambda p: wt.PORTFOLIO_KEYS.get(p, wt.SPY_PORTFOLIO))
    row = ps[(ps["variant"] == variant) & (ps["exit"] == exit_code) & (ps["scope"] == scope) & (pk == portfolio)]
    assert len(row) >= 1
    got = {_py(v) for v in row[stat]}
    if _na(expected):
        assert all(_na(v) for v in got)
    else:
        assert got == {expected}
