"""Point-wise regression on the committed window trace 2026-05-01 -> 2026-06-01 (21 trade days): ONE test
per data point — every 1-minute mark of every event, every event row, every per-share fee, every day of
every daily return / utilization / stop-loss series, every per-scope-per-day event count, every window
statistic of every portfolio, every viewer summary.

Expected values are literals in fixtures/window_2026-05/expected_points.py (GENERATED by
window_trace.py --pointwise, do not edit); inputs are the fixture's parquet files; every recomputation
goes through the producer's own functions:
  A test_event_mark     evaluate.leg_pnl_sum over leg_marks.parquet (weight, entry, mark price of every booked
                        leg, read from the event's 1-minute panel with evaluate.mark_price / exit_price)
                        == baskets.pnl_<mark> (abs 1e-12) == literal (production shard value, exact)
  B test_event_row      rules.direction.fade_the_gap on event_signal.parquet (previous_close, signal_price)
                        == the basket row's gap / direction == literal; status / skip_reason == literal
  C test_fee_row        fees.apply_per_share_fee on the single row == FEE_ROWS literal; every P&L column drops
                        by exactly its fee_per_dollar
  D test_daily_return   window_trace.rebuild_scope (portfolio_analysis.build) == production slice == literal
  E test_daily_utilization  rebuild_scope (portfolio_analysis.build_utilization) == production == literal
  F test_stop_daily     window_trace.rebuild_stop (stop_sim.build) == production stop slice == literal
  G test_event_count    ok / skip rows per scope per trade day (study_config.scope_filter) == literal; totals
  H test_totals         portfolio_analysis.stats_for (window_trace.window_stats: the portfolios composed as
                        portfolio_analysis.build composes them) on the REBUILT window series == the same on the
                        production window slices == literal (abs 1e-9 floats, exact ints / flags / dates);
                        test_fee_drag: gross daily - net daily == the per-day fee drag
                        (portfolio_analysis.daily_multi of fee_per_dollar); test_net_below_gross
  I test_viewer_summary every viewer summary in expected_viewer.json == the H stats (sharpe, total_pct,
                        max_dd_pct; n_trades == the cell's ok rows unless the utilization floor binds)
  test_production_stats (marker pinned_only): the production portfolio_stats_by_exit.parquet rows are
                        FULL-HISTORY statistics (2016-2026, 2,571 trade days); a window trace cannot rebuild
                        them, so they are pinned (fixture parquet == literal), not recomputed.
The module skips when the fixture dir is absent (exported sample).
"""
